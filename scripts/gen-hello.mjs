// Generates src/data/hello.ts: single-stroke cursive paths for the intro
// ("welcome / to my personal blog"), drawn like the macOS "hello" screen.
//
//   node scripts/gen-hello.mjs
//
// Glyphs come from Hershey Script 1-stroke (scripts/fonts/HersheyScript1.svg).
// The Hershey Fonts were originally created by Dr. A. V. Hershey while working
// at the U. S. National Bureau of Standards. The format of the Font data in
// this distribution was originally created by James Hurt, Cognition, Inc.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const LINES = ['welcome', 'to my personal blog'];
const PAD = 40; // room for the round stroke caps

const src = fs.readFileSync(path.join(here, 'fonts/HersheyScript1.svg'), 'utf8');
const defaultAdv = +src.match(/<font[^>]*horiz-adv-x="([\d.]+)"/)[1];
const glyphs = {};
for (const [, attrs] of src.matchAll(/<glyph\s([^>]*?)\/?>/g)) {
  const u = attrs.match(/unicode="([^"]*)"/);
  if (!u || u[1].length !== 1) continue;
  const adv = attrs.match(/horiz-adv-x="([-\d.]+)"/);
  const d = attrs.match(/\sd="([^"]*)"/);
  glyphs[u[1]] = { adv: adv ? +adv[1] : defaultAdv, d: d ? d[1] : '' };
}

// "M x y L x y ..." → arrays of points, one per pen stroke.
function strokes(d) {
  if (!d.trim()) return [];
  const toks = d.trim().split(/[\s,]+/);
  const out = [];
  let cur;
  for (let i = 0; i < toks.length; ) {
    const cmd = /^[A-Za-z]$/.test(toks[i]) ? toks[i++] : 'L';
    const pt = [+toks[i++], +toks[i++]];
    if (cmd === 'M') out.push((cur = [pt]));
    else cur.push(pt);
  }
  return out;
}

// Catmull-Rom through the polyline points, written as cubic Béziers.
const f = (n) => +n.toFixed(1);
function smooth(pts) {
  let s = `M${f(pts[0][0])} ${f(pts[0][1])}`;
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[i - 1] || pts[i], p1 = pts[i], p2 = pts[i + 1], p3 = pts[i + 2] || p2;
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    s += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return s;
}

const lines = LINES.map((text) => {
  let x = 0;
  const all = [];
  const raw = [];
  for (const ch of text) {
    const g = glyphs[ch] ?? glyphs[' '];
    for (const st of strokes(g.d)) {
      const pts = st.map(([px, py]) => [px + x, -py]); // SVG y grows downward
      raw.push(pts);
      all.push(...pts);
    }
    x += g.adv;
  }
  const xs = all.map((p) => p[0]), ys = all.map((p) => p[1]);
  const minX = Math.min(...xs) - PAD, minY = Math.min(...ys) - PAD;
  const w = Math.max(...xs) + PAD - minX, h = Math.max(...ys) + PAD - minY;
  return { text, viewBox: `${f(minX)} ${f(minY)} ${f(w)} ${f(h)}`, width: f(w), height: f(h), paths: raw.map(smooth) };
});

const out = `// Generated by scripts/gen-hello.mjs — do not edit by hand.
// Glyph data: Hershey Script 1-stroke. The Hershey Fonts were originally created
// by Dr. A. V. Hershey while working at the U. S. National Bureau of Standards.
// The format of the Font data in this distribution was originally created by
// James Hurt, Cognition, Inc.

export const helloLines = ${JSON.stringify(lines, null, 2)} as const;
`;
fs.writeFileSync(path.join(here, '../src/data/hello.ts'), out);
console.log(lines.map((l) => `${l.text}: ${l.paths.length} strokes, ${l.width}×${l.height}`).join('\n'));
